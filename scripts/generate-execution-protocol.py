#!/usr/bin/env python3
"""Generate both wire type inventories from the single execution schema."""

import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "runtime/execution/protocol.json"


def words(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).replace("-", "_").lower()


def pascal(name):
    return "".join(word.capitalize() for word in name.split("-"))


def generate():
    schema = json.loads(SCHEMA.read_text())
    digest = hashlib.sha256(SCHEMA.read_bytes()).hexdigest()
    rust = ["// Generated by scripts/generate-execution-protocol.py. Do not edit.",
            "use serde::{Deserialize, Serialize};", "",
            "/// SHA-256 of the exact checked-in protocol schema bytes.",
            f'pub const SCHEMA_DIGEST: &str = "{digest}";', ""]
    ts = ["// Generated by scripts/generate-execution-protocol.py. Do not edit.",
          f'export const schemaDigest = "{digest}";',
          "/** Bind exported metadata to the immutable constraints used by the validator. */",
          "function deepFreeze<T>(value: T): T {",
          '  if (typeof value === "object" && value !== null) {',
          "    for (const child of Object.values(value)) deepFreeze(child);",
          "    Object.freeze(value);",
          "  }",
          "  return value;",
          "}", "",
          "export const schema = deepFreeze(" + json.dumps(schema, ensure_ascii=False, separators=(",", ":")) + " as const);", ""]

    def rust_type(value):
        if isinstance(value, str):
            return "bool" if value == "bool" else value
        if "items" in value:
            return f"Vec<{value['items']}>"
        return "u32"

    def ts_type(value):
        if isinstance(value, str):
            return "boolean" if value == "bool" else value
        if "items" in value:
            return f"{value['items']}[]"
        return json.dumps(value["const"])

    for name, definition in schema["definitions"].items():
        rust.append(f"/// Structural wire representation of `{name}`; decoding validates constraints.")
        if definition.get("type") == "string":
            rust.append(f"pub type {name} = String;")
            ts.append(f"export type {name} = string;")
        elif "enum" in definition:
            rust.extend(["#[derive(Clone, Debug, Eq, PartialEq, Deserialize, Serialize)]", f"pub enum {name} {{"])
            for value in definition["enum"]:
                rust.extend([f"    /// `{value}`.", f"    #[serde(rename = {json.dumps(value)})]", f"    {pascal(value)},"])
            rust.append("}")
            ts.append(f"export type {name} = " + " | ".join(json.dumps(v) for v in definition["enum"]) + ";")
        elif "fields" in definition:
            rust.extend(["#[derive(Clone, Debug, Eq, PartialEq, Deserialize, Serialize)]",
                         '#[serde(rename_all = "camelCase", deny_unknown_fields)]', f"pub struct {name} {{"])
            for field, value in definition["fields"].items():
                rust.extend([f"    /// Wire field `{field}`.", f"    pub {words(field)}: {rust_type(value)},"])
            rust.append("}")
            ts.append(f"export type {name} = {{ " + "; ".join(f"{field}: {ts_type(value)}" for field, value in definition["fields"].items()) + " };")
        elif "variants" in definition:
            rust.extend(["#[derive(Clone, Debug, Eq, PartialEq, Deserialize, Serialize)]",
                         f'#[serde(tag = "{definition["tag"]}")]', f"pub enum {name} {{"])
            for tag, value in definition["variants"].items():
                rust.extend([f"    /// `{tag}`.", f"    #[serde(rename = {json.dumps(tag)})]", f"    {pascal(tag)}({value}),"])
            rust.append("}")
            ts.append(f"export type {name} = " + " | ".join(f'({{ {definition["tag"]}: {json.dumps(tag)} }} & {value})' for tag, value in definition["variants"].items()) + ";")
        else:
            raise ValueError(f"unsupported definition: {name}")
        rust.append("")
        ts.append("")
    return {
        ROOT / "src/execution_protocol/types.rs": "\n".join(rust),
        ROOT / "runtime/execution/types.ts": "\n".join(ts),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, contents in generate().items():
        if args.check:
            if not path.is_file() or path.read_text() != contents:
                raise SystemExit(f"execution protocol drift: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents)


if __name__ == "__main__":
    main()
